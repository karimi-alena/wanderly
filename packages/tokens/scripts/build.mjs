// Builds tokens/*.json into typed React Native theme objects in src/generated/.
import { readdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import StyleDictionary from 'style-dictionary';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const brands = readdirSync(join(root, 'tokens/brands')).map((f) => f.replace('.json', ''));

const WEIGHT_NAMES = { 400: 'Regular', 500: 'Medium', 600: 'SemiBold', 700: 'Bold' };
// Font names as exported by @expo-google-fonts/* packages, e.g. "IBMPlexSans_600SemiBold".
const expoFont = (family, weight) => {
  if (!WEIGHT_NAMES[weight]) throw new Error(`Unsupported font weight ${weight} for ${family}`);
  return `${family.replace(/\s+/g, '')}_${weight}${WEIGHT_NAMES[weight]}`;
};

const header = '// Generated by Style Dictionary from the Figma export. Do not edit; run `npm run tokens`.\n';

function toTree(tokens, valueOf) {
  const tree = {};
  for (const t of tokens) {
    let node = tree;
    for (const key of t.path.slice(0, -1)) node = node[key] ??= {};
    node[t.path.at(-1)] = valueOf(t);
  }
  return tree;
}

StyleDictionary.registerFormat({
  name: 'rn/theme',
  format: ({ dictionary, options }) => {
    const fonts = new Set();
    const tree = toTree(dictionary.allTokens, (t) => {
      if (t.$type !== 'typography') return t.$value;
      const { fontFamily, fontWeight, fontSize, lineHeight, letterSpacing } = t.$value;
      const name = expoFont(fontFamily, Number(fontWeight));
      fonts.add(name);
      return {
        fontFamily: name,
        fontSize,
        lineHeight: Math.round(fontSize * lineHeight),
        letterSpacing: Math.round(fontSize * letterSpacing * 100) / 100,
      };
    });
    // Mono font isn't used by a text style yet; ship its regular weight so code can use it.
    const mono = dictionary.allTokens.find((t) => t.path.join('.') === 'font.family.mono');
    if (mono) fonts.add(expoFont(mono.$value, 400));
    tree.fontFiles = [...fonts].sort();
    return `${header}export const ${options.name} = ${JSON.stringify(tree, null, 2)};\n`;
  },
});

StyleDictionary.registerFormat({
  name: 'rn/dimension',
  format: ({ dictionary }) =>
    `${header}export const dimension = ${JSON.stringify(toTree(dictionary.allTokens, (t) => t.$value).dimension, null, 2)};\n`,
});

const shared = ['tokens/dimension.json', 'tokens/typography.json'].map((f) => join(root, f));

for (const brand of brands) {
  const sd = new StyleDictionary({
    source: [...shared, join(root, `tokens/brands/${brand}.json`)],
    log: { verbosity: 'silent' },
    platforms: {
      rn: {
        transforms: ['name/camel'],
        buildPath: join(root, 'src/generated/'),
        files: [
          {
            destination: `${brand}.ts`,
            format: 'rn/theme',
            options: { name: brand },
            filter: (t) => t.path[0] !== 'dimension',
          },
          ...(brand === brands[0]
            ? [{ destination: 'dimension.ts', format: 'rn/dimension', filter: (t) => t.path[0] === 'dimension' }]
            : []),
        ],
      },
    },
  });
  await sd.buildAllPlatforms();
}
console.log(`Built themes: ${brands.join(', ')} + dimension → src/generated/`);
